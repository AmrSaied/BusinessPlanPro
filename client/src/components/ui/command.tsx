const CommandItem = React.forwardRef<
  React.ElementRef<typeof CommandPrimitive.Item>,
  React.ComponentPropsWithoutRef<typeof CommandPrimitive.Item>
>(({ className, ...props }, ref) => {
  // Check if the component is rendered in an RTL context by checking its content
  // We'll use this approach since we can't access the language context directly here
  const isRTLRegex = /[\u0591-\u07FF\u200F\u202B\u202E\uFB1D-\uFDFD\uFE70-\uFEFC]/;
  const content = typeof props.children === 'string' ? props.children : '';
  const mightBeRTL = isRTLRegex.test(content);
  
  return (
    <CommandPrimitive.Item
      ref={ref}
      className={cn(
        "relative flex cursor-default select-none items-center rounded-sm px-2 py-1.5 text-sm outline-none aria-selected:bg-accent aria-selected:text-accent-foreground data-[disabled]:pointer-events-none data-[disabled]:opacity-50",
        mightBeRTL && "justify-end text-right",
        className
      )}
      dir={mightBeRTL ? "rtl" : "ltr"}
      {...props}
    />
  );
})

CommandItem.displayName = CommandPrimitive.Item.displayName

